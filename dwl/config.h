/* dwl configuration — clean default for a fresh install, paired with Noctalia as the
 * shell/bar. Docs: https://github.com/djpohly/dwl
 *
 * Unlike every other preset in this repo, dwl has no runtime config file: this is a
 * C header compiled into the binary. Copy over dwl's own config.def.h as config.h
 * and `make clean install`. Noctalia itself is launched separately, via dwl's `-s`
 * startup-command flag (see bash_profile.tmpl / LAUNCH_CMD), not from in here.
 *
 * dwl's own tagging/layout model (t/f/m switch layout, 1-9 are tags, not numbered
 * workspaces) is left untouched below — that's the whole point of using dwl over
 * a conventional tiling WM. Only the Noctalia panel toggles, session lock,
 * screenshot and hardware multimedia keys are new, added on MODKEY+CTRL
 * combinations that don't collide with dwl's own defaults (TAGKEYS' toggleview/
 * toggletag only ever use digit/shifted-digit keys, never letters).
 */

